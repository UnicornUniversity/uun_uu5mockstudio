const { contextBridge, ipcRenderer } = require("electron");
const invoke = (ch, ...a) => ipcRenderer.invoke(ch, ...a);
const on = (ch) => (cb) => ipcRenderer.on(ch, (_e, p) => cb(p));
contextBridge.exposeInMainWorld("studio", {
  platform: process.platform,
  info: () => invoke("app:info"),
  claudeStatus: (refresh) => invoke("claude:status", refresh),
  claudeLogin: (opts) => invoke("claude:login", opts),
  claudeInstallerInfo: () => invoke("claude:installerInfo"),
  claudeInstall: () => invoke("claude:install"),
  claudeCancel: (kind) => invoke("claude:cancel", kind),
  claudeInstallPlugins: () => invoke("claude:installPlugins"),
  pluginsCheck: (force) => invoke("plugins:check", force),
  pluginsLater: (u) => invoke("plugins:later", u),
  pluginsUpdate: (ids) => invoke("plugins:update", ids),
  onClaudeProgress: on("claude:progress"),
  registerView: (file, id) => invoke("view:register", file, id),
  unregisterView: (file) => invoke("view:unregister", file),
  saveLayout: (project, layout) => invoke("layout:save", project, layout),
  send: (prompt, model, opts) => invoke("chat:send", { prompt, model, plan: Boolean(opts?.plan) }),
  stop: () => invoke("chat:stop"),
  saveChat: (project, chatId, chat) => invoke("chat:save", project, chatId, chat),
  saveAttachments: (items) => invoke("attachments:save", items),
  listChats: () => invoke("chat:list"),
  switchChat: (id) => invoke("chat:switch", id),
  deleteChat: (id) => invoke("chat:delete", id),
  newChat: () => invoke("chat:new"),
  cdnStatus: () => invoke("cdn:status"),
  cdnSetOffline: (v) => invoke("cdn:offline", v),
  cdnClear: () => invoke("cdn:clear"),
  cdnWarmup: () => invoke("cdn:warmup"),
  onCdnProgress: on("cdn:progress"),
  exportHtml: (file) => invoke("export:html", file),
  exportImage: (file, format) => invoke("export:image", file, format),
  dragPrepare: (kind, file) => invoke("drag:prepare", kind, file),
  dragStart: (p) => ipcRenderer.send("drag:start", p),
  repoLink: () => invoke("repo:link"),
  repoUnlink: () => invoke("repo:unlink"),
  repoFiles: (q) => invoke("repo:files", q),
  repoOpen: () => invoke("repo:open"),
  repoBranches: () => invoke("repo:branches"),
  repoSetBranch: (b) => invoke("repo:setBranch", b),
  rulesGet: () => invoke("rules:get"),
  rulesGetGlobal: () => invoke("rules:getGlobal"),
  rulesSetGlobal: (t) => invoke("rules:setGlobal", t),
  rulesAddGlobal: (t) => invoke("rules:addGlobal", t),
  rulesSet: (t) => invoke("rules:set", t),
  rulesAdd: (t, screen) => invoke("rules:add", t, screen),
  descGet: () => invoke("desc:get"),
  descSet: (t) => invoke("desc:set", t),
  notesGet: (file) => invoke("notes:get", file),
  notesSet: (file, notes) => invoke("notes:set", file, notes),
  notesNewId: (taken) => invoke("notes:newId", taken),
  onMemoryChanged: on("memory:changed"),
  shareMail: (kind, file) => invoke("share:mail", kind, file),
  exportZip: () => invoke("export:zip"),
  reveal: (p) => invoke("reveal", p),
  revealScreen: (file) => invoke("screen:reveal", file),
  deleteScreen: (file) => invoke("screen:delete", file),
  setFullScreen: (on) => invoke("window:fullscreen", on),
  setTheme: (t) => invoke("theme:set", t),
  listProjects: () => invoke("projects:list"),
  closeProject: () => invoke("projects:close"),
  onMenu: on("menu:action"),
  onGlass: on("glass:set"),
  toggleGlass: () => invoke("glass:toggle"),
  openProject: (name) => invoke("projects:open", name),
  createProject: (name) => invoke("projects:create", name),
  renameProject: (from, to) => invoke("projects:rename", from, to),
  deleteProject: (name) => invoke("projects:delete", name),
  revealProject: () => invoke("project:reveal"),
  jsxInspect: (file, ordinals, sub) => invoke("jsx:inspect", { file, ordinals, sub }),
  jsxSet: (file, ordinals, name, type, value, sub) => invoke("jsx:set", { file, ordinals, name, type, value, sub }),
  jsxSetText: (file, ordinals, scope, lang, value) => invoke("jsx:setText", { file, ordinals, scope, lang, value }),
  jsxStructure: (file, ordinal) => invoke("jsx:structure", { file, ordinal }),
  jsxMoves: (file, ops) => invoke("jsx:moves", { file, ops }),
  screenUndo: (file) => invoke("screen:undo", file),
  screenRedo: (file) => invoke("screen:redo", file),
  screenHistory: (file) => invoke("screen:history", file),
  jsxList: (file, ordinals, prop) => invoke("jsx:list", { file, ordinals, prop }),
  jsxItem: (file, ordinals, prop, op) => invoke("jsx:item", { file, ordinals, prop, op }),
  jsxRemove: (file, ordinals, name, sub) => invoke("jsx:remove", { file, ordinals, name, sub }),
  jsxSetBranch: (file, ordinals, name, idx, type, value, sub) => invoke("jsx:setBranch", { file, ordinals, name, idx, type, value, sub }),
  iconCatalog: () => invoke("icons:catalog"),
  uuBml: () => invoke("icons:bml"),
  projectsFolder: (op) => invoke("projects:folder", op),
  meta: () => invoke("app:meta"),
  checkUpdates: () => invoke("update:check"),
  installUpdate: () => invoke("update:install"),
  selfInstallUpdate: () => invoke("update:selfinstall"),
  tourDone: () => invoke("tour:done"),
  docsSearch: (query, library) => invoke("docs:search", query, library),
  docsLibraries: () => invoke("docs:libraries"),
  docsDescribe: (names) => invoke("docs:describe", names),
  docsDetail: (name) => invoke("docs:detail", name),
  docsOpen: (url) => invoke("docs:open", url),
  updateLater: (version) => invoke("update:later", version),
  openUpdate: (url) => invoke("update:open", url),
  onUpdate: on("update:event"),
  openExternal: (url) => invoke("open:external", url),
  onEvent: on("claude:event"),
  onPreviewChanged: on("preview:changed"),
  onNavigated: on("preview:navigated"),
});
