// Regenerates src/renderer/mdiBaseline.js: the names of the Material Design Icons of an older release, which documents may still load.
// The uu5String export warns about mdi-* icons that are not in it. Usage: node scripts/mdi-baseline.mjs [version]
import { writeFile } from "node:fs/promises";
const version = process.argv[2] ?? "4.0.96";
const css = await (await fetch(`https://cdn.jsdelivr.net/npm/@mdi/font@${version}/css/materialdesignicons.min.css`)).text();
const names = [...new Set([...css.matchAll(/\.mdi-([a-z0-9-]+):+before/g)].map((m) => m[1]))].sort();
if (names.length < 1000) throw new Error(`Only ${names.length} icons found: is ${version} a real version?`);
await writeFile(new URL("../src/renderer/mdiBaseline.js", import.meta.url), `// Generated by scripts/mdi-baseline.mjs from @mdi/font ${version} (${names.length} icons). Do not edit by hand.
// Documents (uuBookKit, uuManagementKit) may load this older Material Design Icons font; mdi-* icons that are not here may not show there.
export const MDI_BASELINE_VERSION = "${version}";
export const MDI_BASELINE = new Set("${names.join(" ")}".split(" "));
`);
console.log(`${names.length} icons of ${version}`);
