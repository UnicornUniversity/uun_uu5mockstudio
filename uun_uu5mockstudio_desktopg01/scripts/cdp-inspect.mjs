const ts = await (await fetch(`http://127.0.0.1:${process.env.CDP_PORT ?? 9333}/json`)).json();
const ws = new WebSocket(ts.find((x) => x.type === "page").webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pend = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); pend.get(m.id)?.(m.result); };
const call = (method, params) => new Promise((r) => { pend.set(++id, r); ws.send(JSON.stringify({ id, method, params })); });
const ev = async (expression) => (await call("Runtime.evaluate", { expression, returnByValue: true, awaitPromise: true })).result?.value;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const m = (type, x, y) => call("Input.dispatchMouseEvent", { type, x, y, button: "left", clickCount: 1 });
await ev(`document.getElementById("inspect").click()`); await sleep(1500);
console.log("inspector on:", await ev(`JSON.stringify({panel:!document.getElementById("inspector").hidden,shield:[...document.querySelectorAll(".shield")].map(s=>s.hidden)})`));
const [x, y] = [Number(process.argv[2]), Number(process.argv[3])];
await m("mouseMoved", x, y); await sleep(300); await m("mousePressed", x, y); await m("mouseReleased", x, y); await sleep(800);
console.log("info:", await ev(`document.getElementById("insp-info").innerText`));
await ev(`document.getElementById("insp-use").click()`); await sleep(200);
console.log("chip:", await ev(`document.getElementById("chip").hidden ? "hidden" : document.getElementById("chip").innerText`));
await call("Page.captureScreenshot", { format: "png" }).then(async (s) => (await import("node:fs")).writeFileSync(process.argv[4], Buffer.from(s.data, "base64")));
ws.close();
